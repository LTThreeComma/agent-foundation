def write_python_surface(
    output_dir: Path,
    index: SchemaIndex,
    options: OptionReader,
    descriptor_sha256: str,
) -> list[Path]:
    output_dir.mkdir(parents=True, exist_ok=True)
    records = method_records(index, options)
    outputs = {
        "models.py": render_models(index, options),
        "methods.py": render_methods(records),
        "client.py": render_client(records),
        "codec.py": render_codec(),
        "protocol.py": render_protocol(descriptor_sha256),
        "__init__.py": render_init(index, options),
    }
    paths: list[Path] = []
    for name, content in outputs.items():
        path = output_dir / name
        path.write_text(content, encoding="utf-8")
        paths.append(path)
    return paths
